#!/usr/bin/env python3
"""Rebuild ../data.js for the Storyteller Grimoire.

Downloads:
  * the official character data (roles, night order, jinxes) that The Pandemonium
    Institute publishes for community toolmakers at https://release.botc.app/resources/
  * the most-liked community scripts from https://www.botcscripts.com (public API)

Only scripts made entirely of officially released characters are kept, so every
script in the app is fully playable. Run:  python3 tools/update_data.py [count]
"""
import datetime
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data.js"
RES = "https://release.botc.app/resources/data/{}.json"
API = "https://www.botcscripts.com/api/scripts/?format=json&ordering=-score&page={}"
PLAYABLE = {"townsfolk", "outsider", "minion", "demon"}
BASE_NAMES = {"trouble brewing", "bad moon rising", "sects and violets", "sects & violets"}
WANTED = int(sys.argv[1]) if len(sys.argv) > 1 else 25


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "botc-grimoire-updater"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def norm(i):
    return str(i).lower().replace("_", "").replace("-", "").replace("'", "").replace(" ", "")


def main():
    roles_raw = get(RES.format("roles"))
    night = get(RES.format("nightsheet"))
    jinx_raw = get(RES.format("jinxes"))

    roles = {}
    for r in roles_raw:
        entry = {"name": r["name"], "team": r["team"], "edition": r.get("edition", ""),
                 "ability": r.get("ability", "")}
        if r["team"] in PLAYABLE:
            entry.update({k: v for k, v in {
                "first": r.get("firstNightReminder") or "",
                "other": r.get("otherNightReminder") or "",
                "reminders": r.get("reminders") or [],
            }.items() if v})
        roles[r["id"]] = entry

    jinxes = {}
    for j in jinx_raw:
        for x in j.get("jinx", []):
            jinxes.setdefault(j["id"], {})[x["id"]] = x["reason"]

    scripts, seen, page = [], set(), 1
    while len(scripts) < WANTED and page <= 10:
        data = get(API.format(page))
        for s in data["results"]:
            if s["script_id"] in seen or s["name"].strip().lower() in BASE_NAMES:
                continue
            seen.add(s["script_id"])
            ids = [norm(c["id"] if isinstance(c, dict) else c) for c in s["content"]]
            ids = [i for i in ids if i != "meta"]
            if any(i not in roles for i in ids):
                continue  # uses homebrew characters we have no data for
            play = [i for i in ids if roles[i]["team"] in PLAYABLE]
            if not any(roles[i]["team"] == "demon" for i in play):
                continue
            scripts.append({
                "id": f"c-{s['script_id']}", "name": s["name"], "author": s.get("author") or "",
                "type": s.get("script_type") or "Full", "score": s.get("score") or 0,
                "url": f"https://www.botcscripts.com/script/{s['script_id']}/{s['version']}",
                "ids": ids,
            })
            if len(scripts) >= WANTED:
                break
        if not data.get("next"):
            break
        page += 1

    payload = {"updated": datetime.date.today().isoformat(), "roles": roles,
               "night": night, "jinxes": jinxes, "scripts": scripts}
    OUT.write_text("// Generated by tools/update_data.py. Do not edit by hand.\n"
                   "// Character data (c) The Pandemonium Institute, from https://release.botc.app/resources/\n"
                   "// under its Community Created Content Policy. Scripts from https://www.botcscripts.com\n"
                   "window.BOTC_DATA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"Wrote {OUT} with {len(roles)} roles and {len(scripts)} community scripts.")


if __name__ == "__main__":
    main()
